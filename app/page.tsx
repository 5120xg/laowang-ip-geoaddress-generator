"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import { useMutation } from "@tanstack/react-query";
import { Flex, Box } from "@radix-ui/themes";

import useIP from "@/hooks/useIP";
import useHistory from "@/hooks/useHistory";
import useMail from "@/hooks/useMail";
import { generateIdentity } from "@/services/identityService";
import { isValidIP } from "@/services/ipService";
import { toErrorMessage } from "@/services/http";

import type {
  Address,
  HistoryRecord,
  InputMode,
  Region,
  TempMailMessage,
  User,
} from "@/app/types";

import { InboxDialog } from "./components/InboxDialog";
import { TopBar } from "./components/TopBar";
import { Toast } from "./components/Toast";
import { Header } from "./components/Header";
import { LeftCard } from "./components/LeftCard";
import { RightCard } from "./components/RightCard";

interface CurrentIdentity {
  user: User;
  address: Address;
}

export default function Home() {
  const { ip: currentIP, isLoading: ipLoading, error: ipError } = useIP();
  const {
    history,
    selectedId,
    setSelectedId,
    addRecord,
    toggleStarred,
    deleteRecord,
    deleteAll,
  } = useHistory();
  const mail = useMail();
  const { setSelectedMessage, setToastMessage } = mail;

  const [mode, setMode] = useState<InputMode>("ip");
  const [inputIp, setInputIp] = useState("");
  const [region, setRegion] = useState<Region | null>(null);
  const [current, setCurrent] = useState<CurrentIdentity | null>(null);
  const [error, setError] = useState("");
  const [inboxOpen, setInboxOpen] = useState(false);

  const { mutate: generate, isPending } = useMutation({
    mutationFn: generateIdentity,
    onSuccess: (identity) => {
      setCurrent({ user: identity.user, address: identity.address });
      addRecord(identity);
    },
    onError: (err) => setError(toErrorMessage(err)),
  });

  // 拿到当前 IP 后自动生成一次
  const autoGenerated = useRef(false);
  useEffect(() => {
    if (autoGenerated.current || !currentIP) return;
    autoGenerated.current = true;
    generate({ mode: "ip", ip: currentIP });
  }, [currentIP, generate]);

  const handleGenerate = useCallback(() => {
    setError("");
    if (mode === "region") {
      if (!region) {
        setError("请先选择地区");
        return;
      }
      generate({ mode: "region", region });
      return;
    }

    const target = inputIp.trim() || currentIP;
    if (!target) {
      setError("尚未获取到当前 IP，请手动输入");
      return;
    }
    if (!isValidIP(target)) {
      setError("IP 格式不正确");
      return;
    }
    generate({ mode: "ip", ip: target });
  }, [mode, region, inputIp, currentIP, generate]);

  const handleModeChange = useCallback((next: InputMode) => {
    setMode(next);
    setError("");
  }, []);

  const handleHistoryClick = useCallback(
    (record: HistoryRecord) => {
      setSelectedId(record.id);
      setError("");
      setCurrent({ user: record.user, address: record.address });
    },
    [setSelectedId]
  );

  const handleToastClose = useCallback(
    () => setToastMessage(null),
    [setToastMessage]
  );

  const handleToastClick = useCallback(
    (message: TempMailMessage) => {
      setSelectedMessage(message);
      setToastMessage(null);
      setInboxOpen(true);
    },
    [setSelectedMessage, setToastMessage]
  );

  const resultLoading = isPending || (ipLoading && !current);

  return (
    <Box>
      <TopBar onInboxOpen={() => setInboxOpen(true)} unread={mail.messages.length} />

      <Flex
        className="min-h-screen px-4"
        direction="column"
        align="center"
        justify="center"
        gap="4"
        style={{
          backgroundImage: "var(--background-image)",
          backgroundSize: "var(--background-size)",
          paddingTop: "80px",
          paddingBottom: "24px",
        }}
      >
        <Header ip={currentIP} loading={ipLoading} error={ipError} />

        <Flex
          gap="4"
          direction={{ initial: "column", md: "row" }}
          style={{ width: "100%", maxWidth: "900px" }}
        >
          <LeftCard
            mode={mode}
            onModeChange={handleModeChange}
            inputIp={inputIp}
            onInputIpChange={setInputIp}
            region={region}
            onRegionChange={setRegion}
            currentIP={currentIP}
            isLoading={isPending}
            onGenerate={handleGenerate}
            history={history}
            selectedId={selectedId}
            onHistoryClick={handleHistoryClick}
            onDeleteRecord={deleteRecord}
            onDeleteAll={deleteAll}
            onToggleStarred={toggleStarred}
          />

          <RightCard
            user={current?.user ?? null}
            address={current?.address ?? null}
            isLoading={resultLoading}
            error={error}
            email={mail.tempEmail}
            emailLoading={mail.emailLoading}
            emailError={mail.emailError}
          />
        </Flex>

        <InboxDialog
          open={inboxOpen}
          onOpenChange={setInboxOpen}
          email={mail.tempEmail}
          emailLoading={mail.emailLoading}
          emailError={mail.emailError}
          messages={mail.messages}
          selectedMessage={mail.selectedMessage}
          onMessageClick={setSelectedMessage}
        />

        {mail.toastMessage && (
          <Toast
            key={mail.toastMessage.id}
            message={mail.toastMessage}
            onClose={handleToastClose}
            onClick={handleToastClick}
          />
        )}
      </Flex>
    </Box>
  );
}
